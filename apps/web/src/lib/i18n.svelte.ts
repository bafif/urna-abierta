export const LANGUAGES = { es: 'Español', en: 'English' } as const;
export type Language = keyof typeof LANGUAGES;

const STORAGE_KEY = 'urna-abierta-language';
const dictionaries: Record<Language, Record<MessageKey, string>> = { es, en };

function initial(): Language {
  const saved = typeof localStorage === 'undefined' ? null : localStorage.getItem(STORAGE_KEY);
  // Spanish is the main language: English is chosen, never guessed.
  return saved === 'en' ? 'en' : 'es';
}

let current = $state<Language>(initial());

export const i18n = {
  get language(): Language {
    return current;
  },
  set language(value: Language) {
    current = value;
    localStorage.setItem(STORAGE_KEY, value);
    document.documentElement.lang = value;
  },
};

/** With a count of one it uses the «.one» version of the message, when there is one. */
export function t(key: MessageKey, values: Record<string, string | number> = {}): string {
  const dictionary = dictionaries[current];
  const singular = values.count === 1 ? dictionary[`${key}.one` as MessageKey] : undefined;
  return (singular ?? dictionary[key]).replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''));
}

/** «Martes 6 de abril»: a day as a date, at midday so that no time zone can move it to another day. */
export function formatDay(day: string): string {
  const text = new Date(`${day}T12:00:00`).toLocaleDateString(current, { weekday: 'long', day: 'numeric', month: 'long' });
  return text.charAt(0).toUpperCase() + text.slice(1);
}

/** «6 al 8 de abril», or the dates one by one when they do not follow each other. */
export function formatRange(days: string[]): string {
  if (days.length === 0) return '';
  const date = (day: string) => new Date(`${day}T12:00:00`);
  const short = (day: string) => date(day).toLocaleDateString(current, { day: 'numeric', month: 'long' });
  if (days.length === 1) return short(days[0]!);
  const first = days[0]!;
  const last = days[days.length - 1]!;
  const consecutive = (date(last).getTime() - date(first).getTime()) / 86_400_000 === days.length - 1;
  if (!consecutive) return days.map(short).join(', ');
  if (date(first).getMonth() === date(last).getMonth()) {
    return current === 'es' ? `${date(first).getDate()} al ${short(last)}` : `${short(first)} to ${date(last).getDate()}`;
  }
  return current === 'es' ? `${short(first)} al ${short(last)}` : `${short(first)} to ${short(last)}`;
}

/** «Hace 3 minutos». */
export function timeAgo(moment: string): string {
  const seconds = Math.round((Date.now() - Date.parse(moment)) / 1000);
  const format = new Intl.RelativeTimeFormat(current, { numeric: 'auto' });
  const text =
    Math.abs(seconds) < 60 ? format.format(-Math.max(seconds, 0), 'second') : Math.abs(seconds) < 3600 ? format.format(-Math.round(seconds / 60), 'minute') : Math.abs(seconds) < 86_400 ? format.format(-Math.round(seconds / 3600), 'hour') : format.format(-Math.round(seconds / 86_400), 'day');
  return text.charAt(0).toUpperCase() + text.slice(1);
}

/** What the log says someone did, in words. Something unknown shows as it is rather than disappearing. */
export function actionName(action: string): string {
  const key = `action.${action}` as MessageKey;
  return key in es ? t(key) : action;
}

export function roleName(role: string): string {
  const names: Record<string, MessageKey> = {
    fiscal: 'role.fiscal.detail',
    jefe: 'role.jefe.detail',
    semaforo: 'role.semaforo.detail',
    semaforo_sensible: 'role.semaforo_sensible.title',
    estadistico: 'role.estadistico.detail',
    coordinacion: 'role.coordinacion.detail',
    sistema: 'role.sistema.title',
  };
  const key = names[role];
  return key ? t(key).split(':')[0]! : role;
}

/** «3, 4, 5 y 12 más»: up to four numbers, or the first three and how many more. */
function numberList(lines: number[]): string {
  if (lines.length > 4) return t('roll.where.andMore', { list: lines.slice(0, 3).join(', '), count: lines.length - 3 });
  return lines.length > 1 ? `${lines.slice(0, -1).join(', ')} ${t('roll.where.and')} ${lines[lines.length - 1]}` : String(lines[0] ?? '');
}

/**
 * Problems of one kind in words, all their rows in one line: where they are (a row and its number, or the part of a .padron)
 * and what is wrong. Problems only ever carry a place and a code, never what a row says.
 */
export function rollProblem({ place, problem, lines }: { place: string; problem: string; lines: number[] }): { where: string; text: string } {
  const has = (key: string): key is MessageKey => key in es;
  const many = lines.length > 1;
  const where =
    place === 'file' ? ''
    : place === 'manifest.json' ? `${t('roll.where.manifest')} (manifest.json)`
    : place === 'line' || place === 'electors' || place === 'units' ? t(`roll.where.${place}${many ? '.many' : ''}` as MessageKey, { line: numberList(lines) })
    : place;
  const [code, field] = problem.split(':');
  const fieldKey = `roll.field.${field}`;
  const key: string =
    code === 'invalid' && field ? 'roll.problem.invalidField'
    : code === 'too_long' && field ? 'roll.problem.tooLong'
    // A .padron has lines and its own ids, where a spreadsheet has rows, DNIs and legajos.
    : place !== 'line' && has(`roll.problem.${code}.padron`) ? `roll.problem.${code}.padron`
    : has(`roll.problem.${code}`) ? `roll.problem.${code}`
    : 'roll.problem.other';
  const text = t((many && has(`${key}.many`) ? `${key}.many` : key) as MessageKey, { field: t(has(fieldKey) ? fieldKey : 'roll.field.row') });
  // After the place and a colon, the sentence goes on in lower case.
  return { where, text: where ? text.charAt(0).toLowerCase() + text.slice(1) : text };
}
